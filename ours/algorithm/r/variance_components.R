# Variance components per feature: how much of a feature's variance comes from the gesture, the person,
# the person's own way of doing each gesture, and repetition-to-repetition noise.
#
#   model:  feature ~ gesture + (1 | person) + (1 | person:gesture)        (lme4, REML, feature z-scored)
#   shares: gesture       = variance of the fixed-effect predictions (Nakagawa-style marginal R^2)
#           person        = person intercept variance        (bias of a person across all gestures)
#           person_style  = person x gesture variance        (how this person does this gesture)
#           repetition    = residual variance
#   95 % CI from a parametric bootstrap (bootMer).
#
# Run (from ours/algorithm):  "C:\Program Files\R\R-4.6.1\bin\Rscript.exe" r/variance_components.R [input.csv] [nsim]
# Input: one row per event with columns person, label, and feature columns (scripts/eval_earset.py writes
# results/earset_events.csv). Rows with label 'none' are left out (gestures only).
# Output: results/variance_components.csv and results/variance_components.md

suppressPackageStartupMessages(library(lme4))

args <- commandArgs(trailingOnly = TRUE)
input <- if (length(args) >= 1) args[1] else "results/earset_events.csv"
nsim <- if (length(args) >= 2) as.integer(args[2]) else 100
set.seed(1)

d <- read.csv(input, stringsAsFactors = TRUE)
d <- droplevels(d[d$label != "none", ])
meta_cols <- c("person", "activity", "label", "t_start", "duration_s")
features <- setdiff(names(d), meta_cols)
cat(sprintf("%d events, %d people, gestures: %s, %d features, %d bootstrap draws\n",
            nrow(d), nlevels(d$person), paste(levels(d$label), collapse = "/"), length(features), nsim))

shares <- function(fit) {
  vc <- as.data.frame(VarCorr(fit))
  v_person <- vc$vcov[vc$grp == "person"]
  v_style <- vc$vcov[vc$grp == "person:label"]
  v_res <- vc$vcov[vc$grp == "Residual"]
  v_gesture <- var(as.vector(model.matrix(fit) %*% fixef(fit)))
  tot <- v_gesture + v_person + v_style + v_res
  c(gesture = v_gesture, person = v_person, person_style = v_style, repetition = v_res,
    person_total = v_person + v_style) / tot
}

rows <- list()
for (f in features) {
  y <- d[[f]]
  if (sd(y) == 0 || any(!is.finite(y))) next
  dd <- data.frame(y = as.numeric(scale(y)), label = d$label, person = d$person)
  fit <- suppressMessages(suppressWarnings(
    lmer(y ~ label + (1 | person) + (1 | person:label), data = dd, REML = TRUE)))
  est <- shares(fit)
  boot <- suppressMessages(suppressWarnings(bootMer(fit, shares, nsim = nsim, type = "parametric")))
  ci <- apply(boot$t, 2, quantile, probs = c(0.025, 0.975), na.rm = TRUE)
  rows[[f]] <- data.frame(feature = f,
                          gesture = est[1], gesture_lo = ci[1, 1], gesture_hi = ci[2, 1],
                          person = est[2], person_lo = ci[1, 2], person_hi = ci[2, 2],
                          person_style = est[3], style_lo = ci[1, 3], style_hi = ci[2, 3],
                          repetition = est[4],
                          person_total_hi = ci[2, 5],
                          gesture_over_person = est[1] / (est[2] + est[3]))
  cat(sprintf("  %-16s gesture %.2f  person %.2f  style %.2f  rep %.2f\n", f, est[1], est[2], est[3], est[4]))
}
res <- do.call(rbind, rows)
res <- res[order(-res$gesture_over_person), ]

# Screening rule v2 (fixed before our own data, see r/SCREENING_RULE.md). This run screens all motions at once;
# per-pair screening = run on a CSV filtered to one pair (e.g. tilt_left/tilt_right).
res$keep <- res$gesture >= 0.30 & res$gesture_over_person >= 2 & res$gesture_lo > res$person_total_hi

dir.create("results", showWarnings = FALSE)
write.csv(res, "results/variance_components.csv", row.names = FALSE)

fmt <- function(x, lo, hi) sprintf("%.2f [%.2f, %.2f]", x, lo, hi)
md <- c("# Variance components per feature (R, lme4)", "",
        sprintf("Input `%s`: %d gesture events, %d people, gestures %s. Model `feature ~ gesture + (1|person) + (1|person:gesture)`, feature z-scored; shares of total variance with 95 %% parametric-bootstrap CI (%d draws). Generated by `r/variance_components.R`.",
                input, nrow(d), nlevels(d$person), paste(levels(d$label), collapse = ", "), nsim), "",
        "| feature | gesture | person | person x gesture (style) | repetition | gesture / (person + style) | keep |",
        "|---|---|---|---|---|---|---|")
for (i in seq_len(nrow(res))) {
  r <- res[i, ]
  md <- c(md, sprintf("| %s | %s | %s | %s | %.2f | %.1f | %s |", r$feature,
                      fmt(r$gesture, r$gesture_lo, r$gesture_hi), fmt(r$person, r$person_lo, r$person_hi),
                      fmt(r$person_style, r$style_lo, r$style_hi), r$repetition, r$gesture_over_person,
                      ifelse(r$keep, "yes", "no")))
}
writeLines(md, "results/variance_components.md")
cat("wrote results/variance_components.csv and .md\n")
