"""Does P01's (our app) data help the other people? Leave-one-person-out on the HEAD task, trained WITH and WITHOUT
P01's clips, everything else as in all_data_benchmark.py.  -> results/ablation_p01.md
  python scripts/ablation_p01.py      (from ours/algorithm)
"""
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
src = (HERE / "all_data_benchmark.py").read_text(encoding="utf-8").split('L = ["# All our data')[0]
ns = {"__file__": str(HERE / "all_data_benchmark.py"), "__name__": "adb"}
exec(compile(src, "all_data_benchmark.py", "exec"), ns)
D, run, APPROACHES, ROOT = ns["D"], ns["run"], ns["APPROACHES"], ns["ROOT"]
H = D[D.hd.notna()]
names = [a[0] for a in APPROACHES if a[1] != "rules"]
rows = []
for p in [q for q in H.person.unique() if q != "P01"]:
    te = H[H.person == p]
    for with_p01 in (True, False):
        tr = H[(H.person != p) & (with_p01 | (H.person != "P01"))]
        t2 = te[te.hd.isin(tr.hd.unique())]
        acc = run(tr.index.to_numpy(), t2.index.to_numpy(), "hd")
        rows.append({"test person": p, "P01 in training": "yes" if with_p01 else "no", "train clips": len(tr),
                     "test clips": len(t2), **{n: acc[n] for n in names}})
R = pd.DataFrame(rows)
mean = R.groupby("P01 in training")[names].mean().reset_index().assign(**{"test person": "MEAN"})
diff = (R[R["P01 in training"] == "yes"].set_index("test person")[names]
        - R[R["P01 in training"] == "no"].set_index("test person")[names])
L = ["# Does P01's data help? (leave one person out, HEAD task)", "",
     "Generated by `algorithm/scripts/ablation_p01.py`. Same clips, features and models as all_data_benchmark.py; "
     "only P01's 191 app clips are added to or removed from the training set.", "",
     pd.concat([R, mean], ignore_index=True).round(2).to_markdown(index=False), "",
     "Change from adding P01 (positive = P01's data helped):", "",
     diff.round(2).to_markdown(), "", f"Mean change: " + ", ".join(f"{n}: {diff[n].mean():+.3f}" for n in names), ""]
(ROOT / "results" / "ablation_p01.md").write_text("\n".join(L), encoding="utf-8")
print("\n".join(L))
