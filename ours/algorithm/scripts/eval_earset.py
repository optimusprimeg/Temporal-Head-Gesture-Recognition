"""Full pipeline on EarSet (30 people), leave one person out -> results/earset_pipeline.md

Per person: calibration = quiet level from their `still` recording + head frame from the first 3 nods of their
`nod` recording (those 3 are then excluded). The causal detector runs over every recording; events are labelled
by recording: nod / shake / tilt files -> that gesture, every other file (face, talking, chewing, walking, running,
swallowing, still) -> none. A classifier trained on 29 people classifies the 30th; then the gate and the pair rule.

Worst-case command dictionary: every ordered pair of two DIFFERENT motions among nod / shake / tilt is a command
(6 commands), so any two gated motions of different kinds within the timeout count as a false command.
Also exports results/earset_events.csv (one row per event, all features) for the R analysis.
"""
import sys
import time
from itertools import permutations
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from gesturekit.classify import FeatureLogReg  # noqa: E402
from gesturekit.config import GateConfig, PipelineConfig  # noqa: E402
from gesturekit.decode import Motion, decode, gate  # noqa: E402
from gesturekit.detect import quiet_from  # noqa: E402
from gesturekit.frames import calibrate  # noqa: E402
from gesturekit.features import FEATURE_SETS  # noqa: E402
from gesturekit.io import earset_people, load_earset  # noqa: E402
from gesturekit.pipeline import Calibration, Pipeline  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "results"
OUT.mkdir(exist_ok=True)
HEAD = ["nod", "shake", "tilt"]
OTHER = ["brow-raiser", "brow-lowerer", "wink-l", "wink-r", "eyes-lr", "eyes-ud", "lip-puller", "chin-raiser",
         "mouth-stretch", "speaking", "chewing", "swallowing", "walking", "running", "still"]
ALL_SETS = ("axis", "signed", "timing", "magnitude")
COMMANDS = {(a, b): f"{a}>{b}" for a, b in permutations(HEAD, 2)}
FEATURE_CHOICES = {"axis+signed+timing": ("axis", "signed", "timing"), "all incl. magnitude": ALL_SETS}

t0 = time.time()
rows, store = [], {}  # store[(person, activity)] = (events, duration_s)
for pid in earset_people():
    still, nod = load_earset(pid, "still"), load_earset(pid, "nod")
    if still is None or nod is None:
        continue
    p = Pipeline(PipelineConfig())
    p.cfg.features.sets = ALL_SETS
    q = quiet_from(still, 0, len(still))
    p.calibrations = [Calibration(0.0, q, None)]
    calib_events = p.extract(nod)[:3]  # first 3 nods = calibration, excluded below
    p.calibrations = [Calibration(0.0, q, calibrate(nod, [(e.start, e.end) for e in calib_events], p.cfg.frame))]
    for act in HEAD + OTHER:
        rec = load_earset(pid, act)
        if rec is None:
            continue
        ev = p.extract(rec)
        if act == "nod":
            ev = [e for e in ev if e.t_start >= calib_events[-1].t_end]
        store[(pid, act)] = (ev, len(rec) / rec.fs)
        for e in ev:
            rows.append({"person": pid, "activity": act, "label": act if act in HEAD else "none",
                         "t_start": e.t_start, "duration_s": e.t_end - e.t_start,
                         **dict(zip([n for s in ALL_SETS for n in FEATURE_SETS[s][1]], e.features))})
    print(pid, end=" ", flush=True)
events_df = pd.DataFrame(rows)
events_df.to_csv(OUT / "earset_events.csv", index=False)
print(f"\n{len(events_df)} events, {time.time() - t0:.0f} s")

names_all = [n for s in ALL_SETS for n in FEATURE_SETS[s][1]]
people = sorted(events_df.person.unique(), key=lambda s: int(s[1:]))
GATES = [GateConfig(0.5, 0.1), GateConfig(0.7, 0.3), GateConfig(0.9, 0.6)]
out = ["# Full pipeline on EarSet, leave one person out", "",
       "Generated by `algorithm/scripts/eval_earset.py`. Causal detector (quiet level from the person's still "
       "recording) -> head frame (3 calibration nods) -> features -> logistic regression trained on the other 29 "
       "people -> gate -> pair rule (1.5 s). Worst-case dictionary: all 6 ordered pairs of different motions among "
       "nod/shake/tilt are commands.", "",
       f"{len(events_df)} detected events in {len(store)} recordings of {len(people)} people.", ""]

summary = []
for fname, sets in FEATURE_CHOICES.items():
    cols = [n for s in sets for n in FEATURE_SETS[s][1]]
    idx = [names_all.index(c) for c in cols]
    pred, proba = np.empty(len(events_df), dtype=object), np.zeros((len(events_df), 4))
    for pid in people:
        te = (events_df.person == pid).to_numpy()
        m = FeatureLogReg().model.fit(events_df.loc[~te, cols].to_numpy(), events_df.label[~te])
        proba[te] = m.predict_proba(events_df.loc[te, cols].to_numpy())
        pred[te] = m.classes_[proba[te].argmax(axis=1)]
    classes = list(m.classes_)
    y = events_df.label.to_numpy()
    for g in GATES:
        passed = np.array([gate(pr, pb, classes, g) for pr, pb in zip(pred, proba)])
        head = np.isin(y, HEAD)
        recall = np.mean(passed[head] & (pred[head] == y[head]))
        neg_hours, false_motions, false_cmds = 0.0, 0, 0
        per_act = {}
        for (pid, act), (ev, dur) in store.items():
            if act in HEAD:
                continue
            sel = ((events_df.person == pid) & (events_df.activity == act)).to_numpy()
            mo = [Motion(pr, t, t + d, float(pb.max())) for pr, pb, t, d, ok in
                  zip(pred[sel], proba[sel], events_df.t_start[sel], events_df.duration_s[sel], passed[sel]) if ok]
            c = decode(mo, COMMANDS)
            neg_hours += dur / 3600
            false_motions += len(mo)
            false_cmds += len(c)
            a = per_act.setdefault(act, [0.0, 0, 0])
            a[0] += dur / 3600
            a[1] += len(mo)
            a[2] += len(c)
        summary.append({"features": fname, "gate (min prob, min margin)": f"{g.min_confidence}, {g.min_margin}",
                        "head gestures recognised": recall,
                        "false single motions per hour": false_motions / neg_hours,
                        "false commands per hour": false_cmds / neg_hours,
                        **{f"FC/h {k}": v[2] / v[0] for k, v in per_act.items()
                           if k in ("speaking", "chewing", "walking", "running")}})
    acc = np.mean(pred == y)
    out += [f"Event accuracy ({fname}, before the gate): {acc:.3f}", ""]

res = pd.DataFrame(summary).set_index(["features", "gate (min prob, min margin)"])
out += ["## Gate operating points", "",
        "`head gestures recognised` = share of nod/shake/tilt events that pass the gate with the right name. "
        "False rates are per hour of non-gesture recordings (face, talking, chewing, swallowing, walking, running, "
        "still; about 7.5 h in total). `FC/h <activity>` = false commands per hour during that activity.", "",
        res.to_markdown(floatfmt=".2f"), "",
        "Caveats: EarSet head files repeat one gesture for 2 minutes, so command *recall* cannot be measured here "
        "(only false commands). One custom earbud. Walking/running were on a treadmill. Talking was a conversation "
        "while seated.", ""]
(OUT / "earset_pipeline.md").write_text("\n".join(out), encoding="utf-8")
print("\n".join(out))
