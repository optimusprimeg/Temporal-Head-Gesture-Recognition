"""Can a filter make micro-gestures (jaw, face) usable on an earbud IMU? -> results/micro_filters.md

Idea: head motion is slow (rotation mostly below ~3 Hz). Jaw / face muscles add small, faster vibration. So split
each window into frequency bands (band-pass) and ask in which band the micro-gesture stands out.
Band power = log energy of the (mean-removed, Hann-windowed) signal inside each band, rotation and acceleration
separately.

A. Real AirPods Pro 2 (old takes, 4 people, 50 Hz): jaw clench (single + double) vs idle, per band, AUC per person
   (0.5 = cannot tell apart, 1.0 = perfectly apart). Shows which band carries the clench on the actual device.
B. EarSet (30 people, left ear): each face action vs EVERYDAY windows (still + speaking + chewing, their most active
   windows = the hard case for false triggers). Leave one person out, logistic regression, balanced accuracy.
   Feature sets:  base 50 Hz (the earlier face test's features), + bands 50 Hz (AirPods rate), + bands 100 Hz
   (what a faster sensor would add).
Run from ours/algorithm: python scripts/micro_filters.py
"""
import sys
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import balanced_accuracy_score, roc_auc_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from gesturekit.io import earset_people, load_earset, load_old_takes  # noqa: E402

BANDS = [(0.3, 3), (3, 8), (8, 15), (15, 25), (25, 50)]
FACE = ["brow-raiser", "brow-lowerer", "wink-l", "wink-r", "eyes-lr", "eyes-ud", "lip-puller", "chin-raiser",
        "mouth-stretch"]
EVERYDAY = ["still", "speaking", "chewing"]


def bandpow(x, fs):
    x = x - x.mean(0)
    P = np.abs(np.fft.rfft(x * np.hanning(len(x))[:, None], axis=0)) ** 2
    f = np.fft.rfftfreq(len(x), 1 / fs)
    return [float(np.log(P[(f >= a) & (f < b)].sum() + 1e-12)) for a, b in BANDS if b <= fs / 2 + 1e-9]


def band_names(fs):
    return [f"{s}_{a:g}-{b:g}Hz" for s in ("rot", "acc") for a, b in BANDS if b <= fs / 2 + 1e-9]


L = ["# Filters for micro-gestures (jaw, face)", "", "Generated by `algorithm/scripts/micro_filters.py` (method in its "
     "header). Band = band-pass energy of rotation or acceleration in that frequency range.", ""]

# ------------------------------------------------------------------ A. AirPods jaw clench vs idle
rows = []
for s in (1, 2, 3, 4):
    for r in load_old_takes(s):
        lab = r.meta["label"]
        if lab in ("idle", "jaw_clench_single", "jaw_clench_double"):
            rows.append({"person": s, "jaw": lab != "idle",
                         **dict(zip(band_names(50), bandpow(r.rot, 50) + bandpow(r.acc, 50)))})
A = pd.DataFrame(rows)
res = []
for c in band_names(50):
    res.append({"band": c, **{f"P{p}": round(roc_auc_score(d.jaw, d[c]), 2) for p, d in A.groupby("person")},
                "jaw / idle energy (median)": round(float(np.exp(A[A.jaw][c].median() - A[~A.jaw][c].median())), 1)})
RA = pd.DataFrame(res)
L += ["## A. Real AirPods Pro 2: jaw clench vs idle (4 people, 50 Hz)", "",
      f"{int(A.jaw.sum())} clench takes, {int((~A.jaw).sum())} idle takes. AUC per person (0.5 = no difference).", "",
      RA.to_markdown(index=False), ""]
print("\n".join(L[-4:]))

# ------------------------------------------------------------------ B. EarSet face actions vs everyday


def window_feats(rec, a, b, fs):
    rot, acc = np.nan_to_num(rec.rot[a:b]), np.nan_to_num(rec.acc[a:b])
    rm, am = np.linalg.norm(rot, axis=1), np.linalg.norm(acc, axis=1)
    hf = np.linalg.norm(np.diff(acc, axis=0), axis=1)
    base = [rm.mean(), rm.max(), am.mean(), am.max(), hf.mean(), hf.max()]
    base += list(np.sqrt((rot ** 2).mean(0))) + list(np.sqrt((acc ** 2).mean(0)))
    return base, bandpow(rot, fs) + bandpow(acc, fs)


def top_windows(rec, fs, n=12):
    win = int(1.5 * fs)
    sc = np.nan_to_num(np.linalg.norm(rec.rot, axis=1)) / 0.02 + np.nan_to_num(np.linalg.norm(rec.acc, axis=1)) / 0.05
    starts = list(range(0, max(len(sc) - win, 0), int(0.25 * fs)))
    s = np.array([sc[x:x + win].mean() for x in starts])
    chosen = []
    for i in np.argsort(s)[::-1]:
        if all(abs(starts[i] - starts[j]) >= win for j in chosen):
            chosen.append(i)
        if len(chosen) == n:
            break
    return [(starts[i], starts[i] + win) for i in chosen]


rows = []
for pid in earset_people():
    for act in FACE + EVERYDAY:
        r50, r100 = load_earset(pid, act, "left", 50.0), load_earset(pid, act, "left", 100.0)
        if r50 is None:
            continue
        for a, b in top_windows(r50, 50):
            base, b50 = window_feats(r50, a, b, 50)
            _, b100 = window_feats(r100, 2 * a, 2 * b, 100)
            rows.append({"person": pid, "action": act, "base": base, "b50": b50, "b100": b100})
    print(pid, end=" ", flush=True)
print()
B = pd.DataFrame(rows)
y_act, grp = B.action.to_numpy(), B.person.to_numpy()
SETS = {"base 50 Hz": np.array(B.base.tolist()),
        "base + bands, 50 Hz (AirPods)": np.hstack([np.array(B.base.tolist()), np.array(B.b50.tolist())]),
        "base + bands, 100 Hz": np.hstack([np.array(B.base.tolist()), np.array(B.b100.tolist())])}


def loso_binary(X, pos, mask):
    y = (y_act == pos)
    pred = np.zeros(len(y), bool)
    for p in np.unique(grp[mask]):
        tr, te = mask & (grp != p), mask & (grp == p)
        m = make_pipeline(StandardScaler(), LogisticRegression(max_iter=3000, C=0.5, class_weight="balanced"))
        pred[te] = m.fit(X[tr], y[tr]).predict(X[te])
    return balanced_accuracy_score(y[mask], pred[mask]), float(pred[mask & ~y].mean()), float(pred[mask & y].mean())


res = []
ev = np.isin(y_act, EVERYDAY)
for act in FACE:
    mask = ev | (y_act == act)
    r = {"action": act}
    for name, X in SETS.items():
        ba, fp, hit = loso_binary(X, act, mask)
        r[name] = f"{ba:.2f} (hit {hit:.2f}, false {fp:.2f})"
    res.append(r)
RB = pd.DataFrame(res)
# which band separates each action from talking best (single-feature AUC, 100 Hz)
names100 = band_names(100)
X100 = np.array(B.b100.tolist())
best = []
for act in FACE:
    m = np.isin(y_act, [act, "speaking", "chewing"])
    aucs = [roc_auc_score(y_act[m] == act, X100[m, j]) for j in range(len(names100))]
    j = int(np.argmax(np.abs(np.array(aucs) - 0.5)))
    best.append({"action": act, "best band vs talking/chewing": names100[j], "AUC": round(aucs[j], 2)})
L += ["## B. EarSet (30 people, left ear): face action vs everyday (still + speaking + chewing)", "",
      "Leave one person out. Balanced accuracy (0.5 = chance); hit = action windows caught; false = everyday "
      "windows that would trigger. The everyday windows are each recording's most active ones (hard case).", "",
      RB.to_markdown(index=False), "", "Single best band against talking and chewing (100 Hz data):", "",
      pd.DataFrame(best).to_markdown(index=False), ""]
out = ROOT / "results" / "micro_filters.md"
out.write_text("\n".join(L), encoding="utf-8")
print("\n".join(L))
