rng = np.random.default_rng(0)
L = ["# Micro-gesture ideas tested on existing data", "",
     "Generated by `algorithm/scripts/micro_ideas.py` (method in its header).", ""]

# ====================================================================== T1 shrink head motions
SESSION = (ROOT.parent / "data" / "internal GG 01" / "P01_ghanshyam_s1_airpodspro2_20261107_024251" /
           "P01_ghanshyam_s1_airpodspro2_20261107_024251")
rec, p, ev, _, _ = pr.session_events(str(SESSION), 1.5)
cues = rec.cues.copy()
cues.loc[cues.kind == "practice", "kind"] = "rounds"
labels, _ = label_events(ev, cues, p.cfg.label)
motions = [(e, lab) for e, lab in zip(ev, labels) if lab in pr.MOTIONS]
cal = p.calibrations[0]
t_still = float(rec.cues[(rec.cues.kind == "calibration") & (rec.cues.motion == "still")].t_s.iloc[0])
a0, b0 = rec.index(t_still + 0.5), rec.index(t_still + 3.5)
n_acc, n_rot = to_head(rec, a0, b0, cal.frame)
FS = rec.fs
sp, jk = np.linalg.norm(n_rot, axis=1), np.r_[0, np.linalg.norm(np.diff(n_acc, axis=0), axis=1)]
QUIET = Quiet(float(np.median(sp)) + 1e-4, float(np.median(jk)) + 1e-4, 0.0)
QUIET.score = float(np.median(sp / QUIET.rot + jk / QUIET.jerk))
print(f"T1: {len(motions)} motions, still noise {len(n_rot) / FS:.1f} s, quiet rot {QUIET.rot:.4f} rad/s")


def noise(n):
    """n samples of real still noise (random circular offset into the 3 s still pose)."""
    i = (rng.integers(len(n_rot)) + np.arange(n)) % len(n_rot)
    return n_acc[i], n_rot[i]


rows = []
for scale in [1.0, 0.5, 0.3, 0.2, 0.1, 0.05]:
    for e, lab in motions:
        ang = np.degrees(np.linalg.norm(np.cumsum(e.rot, axis=0) / FS, axis=1).max())
        for _ in range(5):
            pad = int(1.0 * FS)
            na, nr = noise(len(e.rot) + 2 * pad)
            acc = na.copy()
            rot = nr.copy()
            acc[pad:pad + len(e.rot)] += scale * e.acc
            rot[pad:pad + len(e.rot)] += scale * e.rot
            det = Detector(DetectorConfig(fs=FS), QUIET)
            found = []
            for i in range(len(rot)):
                found += det.push(rot[i], acc[i])
            found += det.flush()
            hit = any(a < pad + len(e.rot) and b > pad for a, b in found)
            f = of.features_from_head(acc[pad:pad + len(e.rot)], rot[pad:pad + len(e.rot)], FS)
            rows.append({"scale": scale, "motion": lab, "angle_deg": ang * scale, "detected": hit,
                         "named right": of.rule_classify(f) == lab,
                         "kind right": of.rule_kind(f) == of.rule_kind(of.features_from_head(e.acc, e.rot, FS))})
S1 = pd.DataFrame(rows)
T1 = S1.groupby("scale", sort=False).agg(**{"peak angle (deg, median)": ("angle_deg", "median"),
                                            "detector fires": ("detected", "mean"),
                                            "kind kept (nod/tilt/turn/circle)": ("kind right", "mean"),
                                            "named right (rules)": ("named right", "mean")}).round(2)
T1b = S1.pivot_table(index="motion", columns="scale", values="named right", aggfunc="mean").round(2)
T1b = T1b[sorted(T1b.columns, reverse=True)]
L += ["## T1. How small can a head motion be? (P01, AirPods Pro 2, real still noise)", "",
      "Each of P01's 28 motions shrunk and laid on real still noise, 5 noise draws each. 'named right' uses the "
      "live rules with the P01 calibration. At scale 1.0 the rules are P01's own development thresholds.", "",
      T1.to_markdown(), "", "Named right, per motion and scale:", "", T1b.to_markdown(), ""]
print("\n".join(L[-8:]), flush=True)

# ====================================================================== T2 shape change during face gestures
MF = REPO / "micro_gesture_dataset_100hz.csv"
d = pd.read_csv(MF).sort_values(["session_id", "timestamp"])
FSm = 50


def qangle(q, q0):
    return np.degrees(2 * np.arccos(np.clip(np.abs(q @ q0), 0, 1)))


rows = []
for cid, g in d.groupby("session_id"):
    if len(g) < FSm:
        continue
    q = g[["quatX", "quatY", "quatZ", "quatW"]].to_numpy(float).copy()
    q /= np.linalg.norm(q, axis=1, keepdims=True)
    rot = g[["rotX", "rotY", "rotZ"]].to_numpy(float)
    k = int(0.4 * FSm)
    i0 = int(np.argmin(np.convolve(np.linalg.norm(rot, axis=1), np.ones(k), "valid")))
    q0 = q[i0 + k // 2]
    ang = uniform_filter1d(qangle(q, q0), 5)
    peak = ang.max()
    above = ang > 0.5 * peak
    runs = np.split(np.where(above)[0], np.where(np.diff(np.where(above)[0]) > 1)[0] + 1) if above.any() else [[]]
    longest = max(len(r) for r in runs) / FSm
    gdir = g[["gravX", "gravY", "gravZ"]].to_numpy(float).copy()
    gdir /= np.linalg.norm(gdir, axis=1, keepdims=True)
    tilt = np.degrees(np.arccos(np.clip(gdir @ gdir[i0 + k // 2], -1, 1)))
    gm = gdir.mean(0)
    static = {"peak_angle_deg": peak, "mean_angle_deg": ang.mean(), "longest_hold_s": longest,
              "share_time_above_half": above.mean(), "peak_tilt_deg": tilt.max(),
              "angle_per_rotation": peak / (np.degrees(np.abs(rot).sum(0).max() / FSm) + 1e-6)}
    rows.append({"clip": cid, "label": g.label.iloc[0].replace("_2x", "").replace("_", " "), "t0": g.timestamp.iloc[0],
                 "static": static, "ours": of.event_features(g, FSm),
                 "posture": list(gm) + list(g[["yaw", "pitch", "roll"]].mean())})
T = pd.DataFrame(rows).sort_values(["label", "t0"]).reset_index(drop=True)
ST = pd.DataFrame(T.static.tolist())
order_cls = list(dict.fromkeys(T.sort_values("t0").label))
T2a = ST.groupby(T.label).median().reindex(order_cls).round(2)
y = T.label.to_numpy()
order = (T.groupby("label").cumcount() / T.groupby("label").label.transform("size")).to_numpy()
OUR = of.FEATURES_CORE + of.FEATURES_DIRECTION + of.FEATURES_TIMING + of.FEATURES_MAGNITUDE
X_our = pd.DataFrame(T.ours.tolist())[OUR].to_numpy()
X_st = ST.to_numpy()
SETS = {"ours (25)": X_our, "static only (6)": X_st, "ours + static (31)": np.hstack([X_our, X_st]),
        "posture-only check": np.array(T.posture.tolist())}
res = []
for name, X in SETS.items():
    tr, te = order < 0.6, order >= 0.6
    pt = RandomForestClassifier(300, random_state=0, n_jobs=-1).fit(X[tr], y[tr]).predict(X[te])
    res.append({"features": name, "by time (last 40 %)": round(float(np.mean(pt == y[te])), 2),
                **{c: round(float(np.mean(pt[y[te] == c] == c)), 2) for c in order_cls}})
L += ["## T2. Shape change during face gestures (micro-gesture file, one person, AirPods)", "",
      "Angle = how far the earbud's fused orientation moves from the clip's quietest moment. longest_hold_s = "
      "longest stretch above half the peak. angle_per_rotation = peak angle / largest single-axis rotation: "
      "near 1 = the bud turned and stayed, small = it shook and came back.", "", T2a.to_markdown(), "",
      "Naming the 7 gestures, split by time (first 60 % of each gesture train, last 40 % test):", "",
      pd.DataFrame(res).to_markdown(index=False), ""]
print("\n".join(L[-10:]), flush=True)

# ====================================================================== T3 swallow on EarSet
FS3, W = 50, 100


def envelope(r):
    g = np.nan_to_num(np.linalg.norm(r.rot, axis=1))
    j = np.r_[0, np.nan_to_num(np.linalg.norm(np.diff(r.acc, axis=0), axis=1))]
    return uniform_filter1d(g / (np.median(g) + 1e-6) + j / (np.median(j) + 1e-6), int(0.3 * FS3))


def beats(env):
    e = env - env.mean()
    ac = np.correlate(e, e, "full")[len(e) - 1:]
    lo, hi = int(3.5 * FS3), int(7 * FS3)
    T_ = lo + int(np.argmax(ac[lo:hi]))
    tol = int(0.4 * FS3)
    best, phase = -1, 0
    for ph in range(0, T_, 5):
        s = sum(env[max(0, c - tol):c + tol].max() for c in range(ph, len(env) - tol, T_))
        if s > best:
            best, phase = s, ph
    cs = []
    for c in range(phase, len(env), T_):
        a, b = max(0, c - FS3), min(len(env), c + FS3)
        m = a + int(np.argmax(env[a:b]))
        if m - W // 2 >= 0 and m + W // 2 + T_ // 2 <= len(env):
            cs.append(m)
    return T_, cs


def bandpow(x):
    x = x - x.mean(0)
    P = np.abs(np.fft.rfft(x * np.hanning(len(x))[:, None], axis=0)) ** 2
    f = np.fft.rfftfreq(len(x), 1 / FS3)
    return [np.log(P[(f >= a) & (f < b)].sum() + 1e-9) for a, b in [(0.3, 3), (3, 8), (8, 15), (15, 25)]]


def wfeat(r, c):
    a = c - W // 2
    rot, acc = np.nan_to_num(r.rot[a:a + W]), np.nan_to_num(r.acc[a:a + W])
    rm, am = np.linalg.norm(rot, axis=1), np.linalg.norm(acc, axis=1)
    return (list(np.log(np.sqrt((rot ** 2).mean(0)) + 1e-6)) + list(np.log(np.sqrt((acc ** 2).mean(0)) + 1e-6))
            + bandpow(rot) + bandpow(acc) + [np.log(rm.max() + 1e-6), np.log(am.max() + 1e-6)])


rows = []
for pid in earset_people():
    for act in ["swallowing", "speaking", "chewing"]:
        r = load_earset(pid, act, "left", FS3)
        if r is None:
            continue
        if act == "swallowing":
            T_, cs = beats(envelope(r))
            pairs = [(c, "rep") for c in cs] + [(c + T_ // 2, "rest") for c in cs]
            env = envelope(r)
        else:
            pairs = [(c, "everyday") for c in range(W // 2, len(r.t) - W // 2, FS3)]
        for c, kind in pairs:
            if c + W // 2 <= len(r.t):
                rows.append({"person": pid, "kind": kind, "act": act, "f": wfeat(r, c),
                             "env": float(envelope(r)[c - W // 2:c + W // 2].mean()) if act == "swallowing" else np.nan,
                             "period": T_ / FS3 if act == "swallowing" else np.nan})
    print(pid, end=" ", flush=True)
print()
D3 = pd.DataFrame(rows)
X3 = np.array(D3.f.tolist())
pos, neg, pp = (D3.kind == "rep").to_numpy(), D3.kind.isin(["rest", "everyday"]).to_numpy(), D3.person.to_numpy()
hit, fa, fa_talk = [], [], []
for pid in D3.person.unique():
    tr = (pos | neg) & (pp != pid)
    m = RandomForestClassifier(300, random_state=0, n_jobs=-1, class_weight="balanced").fit(X3[tr], pos[tr])
    thr = np.quantile(m.predict_proba(X3[neg & (pp != pid)])[:, 1], 0.99)
    tp, tn = pos & (pp == pid), neg & (pp == pid)
    if tp.sum() == 0:
        continue
    hit.append(np.mean(m.predict_proba(X3[tp])[:, 1] > thr))
    fa.append(np.mean(m.predict_proba(X3[tn])[:, 1] > thr))
    tt = tn & D3.act.isin(["speaking", "chewing"]).to_numpy()
    fa_talk.append(np.mean(m.predict_proba(X3[tt])[:, 1] > thr))
sw = D3[D3.act == "swallowing"]
ratio = sw[sw.kind == "rep"].env.median() / sw[sw.kind == "rest"].env.median()
L += ["## T3. Swallow as a gesture (EarSet, 30 people, left ear, new person)", "",
      f"- beat found: {sw.period.median():.1f} s (median); repetitions: {int(pos.sum())}",
      f"- activity, repetition vs rest between them: {ratio:.2f}x (mouth stretch 2.85x, head motions 8-19x, "
      "other face actions 1.1-1.4x)",
      f"- caught: {np.mean(hit):.2f}; false windows (rest + talking + chewing): {np.mean(fa):.3f}; "
      f"talking/chewing windows only: {np.mean(fa_talk):.3f}", ""]
out = ROOT / "results" / "micro_ideas.md"
out.write_text("\n".join(L), encoding="utf-8")
print("\n".join(L))
