"""Three micro-gesture ideas, tested on data we already have -> results/micro_ideas.md

T1  HOW SMALL CAN A HEAD MOTION BE?  P01's real AirPods motions (8 single motions, app session, head frame) are
    shrunk to 50 / 30 / 20 / 10 / 5 % of their size and laid on top of REAL AirPods still noise (P01's calibration
    still pose, same head frame). Per size: peak angle (degrees), does our detector fire (quiet level from the same
    still noise, as in the app), and do our live rules name it correctly (event = the motion's own span).
    Real small motions also slow down and change shape, so this is the noise floor, not a person: it says where
    the SENSOR stops seeing a motion, the person data says the rest. One person, 28 motions.
T2  SHAPE-CHANGE DURING A FACE GESTURE.  The earbud sits in the ear canal: opening the jaw or puffing the cheeks
    changes the canal and tips the bud for as long as the face holds the pose. Measured from the fused orientation
    (quaternion): angle from the clip's quietest moment, its peak, and how long it stays above half its peak
    (plateau). Then: does adding these 'static' features help name the 7 face gestures (micro-gesture file,
    split by time), compared with the posture-only check?
T3  SWALLOW AS A GESTURE (EarSet, 30 people, left ear).  Repetitions found on the ~5 s beat (as in
    face_gestures_v2.py); detected against rest + talking + chewing windows, leave one person out, threshold at 1 %
    of the training people's everyday windows.
Run from ours/algorithm: python scripts/micro_ideas.py
"""
