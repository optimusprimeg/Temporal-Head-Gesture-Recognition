"""Phase 0 analysis on EarSet bouts -> results/phase0_report.md

A. Signal strength: how visible is each motion to an in-ear IMU.
B. Variance split per feature (head motions): gesture vs person-within-gesture vs repetition, per frame.
C. Leave-one-person-out classification, per frame: nod/shake/tilt, and nod/shake/tilt/none.
Run build_bouts.py first.
"""
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import f1_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from earset import FACE, HEAD, NEGATIVE
from features import NAMES

OUT = Path(__file__).resolve().parent / "results"
df = pd.read_csv(OUT / "bouts.csv")
recs = pd.read_csv(OUT / "recordings.csv")
FRAMES = {"R0": "sensor axes", "R1": "gravity frame", "R2": "head frame (3 calibration nods)"}
out = ["# Phase 0: EarSet (30 people, in-ear IMU, left ear)", "",
       "Generated by `phase0/analyse.py` from `results/bouts.csv` (`phase0/build_bouts.py`). "
       "A bout = one burst of motion above the person's own quiet level (from their `still` recording), cut "
       "automatically (`phase0/segment.py`); continuous motion is split into pieces of at most 12 s. The first 3 nod "
       "bouts per person are used only to find the head frame and are left out of everything below. Bouts are cut "
       "offline from whole recordings, so this tests the classifier, not a live detector.", ""]

# ---------------- A. signal strength ----------------
n_people = df.person.nunique()
sig = df.groupby("activity").agg(people=("person", "nunique"), bouts=("bout", "size"),
                                 peak_rotation_rad_s=("R0_peak_rot", "median"),
                                 acc_rms_g=("R0_acc_per_rot", lambda s: np.nan))
sig["acc_rms_g"] = (df.R0_acc_per_rot * df.R0_rms_rot).groupby(df.activity).median()
sig["bouts_per_person"] = sig.bouts / n_people
group = {**{a: "head" for a in HEAD}, **{a: "face" for a in FACE}, **{a: "negative" for a in NEGATIVE}}
sig.insert(0, "group", sig.index.map(group))
sig = sig.sort_values("peak_rotation_rad_s", ascending=False)
out += ["## A. How visible is each motion", "",
        "Head motions were cued about every 5 s (about 24 bursts per 2-minute file, judged from the plots; EarSet "
        "does not state the count). For face motions, few bouts per person means most of them did not rise above "
        "the person's still level. For negatives (talking, walking, ...) bouts are simply what a detector would "
        "fire on.", "",
        sig.drop(columns="bouts").to_markdown(floatfmt=".2f"), ""]

# ---------------- B. variance split ----------------
head = df[df.activity.isin(HEAD)].copy()


def variance_split(d, col):
    x = d[col].to_numpy()
    tot = ((x - x.mean()) ** 2).sum()
    g_mean = d.groupby("activity")[col].transform("mean")
    c_mean = d.groupby(["activity", "person"])[col].transform("mean")
    return {"gesture": ((g_mean - x.mean()) ** 2).sum() / tot,
            "person": ((c_mean - g_mean) ** 2).sum() / tot,
            "repetition": ((x - c_mean) ** 2).sum() / tot}


rows = []
for fr in FRAMES:
    for n in NAMES:
        v = variance_split(head, f"{fr}_{n}")
        rows.append({"frame": fr, "feature": n, **v, "gesture_over_person": v["gesture"] / max(v["person"], 1e-9)})
vs = pd.DataFrame(rows)
axis_rows = vs[vs.feature.str.startswith("share_")]
out += ["## B. What a feature measures: the gesture or the person?", "",
        "Share of each feature's variance (nod, shake, tilt bouts) explained by the gesture, by the person "
        "(person-to-person differences within the same gesture) and by repetition-to-repetition noise. "
        "A good feature has a large `gesture` share and a small `person` share.", "",
        "### Axis features in the three frames", "",
        axis_rows.set_index(["feature", "frame"]).sort_index().to_markdown(floatfmt=".2f"), "",
        "### All features, head frame (R2), best first", "",
        vs[vs.frame == "R2"].sort_values("gesture_over_person", ascending=False)
        .set_index("feature").drop(columns="frame").to_markdown(floatfmt=".2f"), ""]

# ---------------- C. leave one person out ----------------


def loso(d, labels, cols):
    pred = np.empty(len(d), dtype=object)
    persons = d.person.to_numpy()
    X = d[cols].to_numpy()
    for p in np.unique(persons):
        te = persons == p
        m = make_pipeline(StandardScaler(), LogisticRegression(max_iter=2000, class_weight="balanced"))
        pred[te] = m.fit(X[~te], labels[~te]).predict(X[te])
    return pred


tasks = {"3 head gestures": (head, head.activity.to_numpy()),
         "3 head gestures + none": (df, np.where(df.activity.isin(HEAD), df.activity, "none"))}
rows, per_person, preds = [], {}, {}
for tname, (d, y) in tasks.items():
    for fr in FRAMES:
        pred = loso(d, y, [f"{fr}_{n}" for n in NAMES])
        preds[(tname, fr)] = pred
        r = {"task": tname, "frame": f"{fr} {FRAMES[fr]}", "accuracy": np.mean(pred == y),
             "macro_F1": f1_score(y, pred, average="macro")}
        for c in sorted(set(y)):
            r[f"recall_{c}"] = np.mean(pred[y == c] == c)
        if "none" in set(y):
            r["none_called_gesture"] = np.mean(pred[y == "none"] != "none")
        rows.append(r)
        per_person[(tname, fr)] = pd.Series(pred == y).groupby(d.person.to_numpy()).mean()
res = pd.DataFrame(rows).set_index(["task", "frame"])

tests = []
for tname in tasks:
    for a, b in [("R1", "R0"), ("R2", "R0"), ("R2", "R1")]:
        pa, pb = per_person[(tname, a)], per_person[(tname, b)]
        tests.append({"task": tname, "comparison": f"{a} vs {b}", "mean_gain": (pa - pb).mean(),
                      "people_better": int((pa > pb).sum()), "people_worse": int((pa < pb).sum()),
                      "wilcoxon_p": wilcoxon(pa, pb).pvalue})
spread = pd.DataFrame({f"{t} / {fr}": s.describe()[["min", "25%", "50%", "max"]]
                       for (t, fr), s in per_person.items()}).T
out += ["## C. Leave one person out (train on 29 people, test on the 30th)", "",
        f"Logistic regression on the {len(NAMES)} features above, nothing tuned. `none` = every bout from the face "
        "and negative recordings (speaking, chewing, walking, ...), i.e. motion that must not become a message.", "",
        res.to_markdown(floatfmt=".2f"), "",
        "### Does the frame matter? Paired over the 30 people", "",
        pd.DataFrame(tests).set_index(["task", "comparison"]).to_markdown(floatfmt=".3f"), "",
        "### Accuracy per test person", "", spread.to_markdown(floatfmt=".2f"), ""]

# false alarms by source, head frame: called a gesture / hours of that activity actually recorded
pred = preds[("3 head gestures + none", "R2")]
neg = ~df.activity.isin(HEAD).to_numpy()
fa = pd.DataFrame({"activity": df.activity[neg], "called": pred[neg]})
fa_tab = fa.groupby("activity").agg(bouts=("called", "size"),
                                    called_gesture=("called", lambda s: int((s != "none").sum())))
fa_tab["share_called_gesture"] = fa_tab.called_gesture / fa_tab.bouts
hours = recs.groupby("activity").minutes.sum() / 60
fa_tab["hours_recorded"] = hours.reindex(fa_tab.index)
fa_tab["false_messages_per_hour"] = fa_tab.called_gesture / fa_tab.hours_recorded
fa_tab["most_common_wrong_label"] = fa.groupby("activity")["called"].agg(
    lambda s: s[s != "none"].mode().iloc[0] if (s != "none").any() else "")
out += ["### Where false messages would come from (head frame, 4-class task)", "",
        "`false_messages_per_hour` = bouts wrongly called a gesture / hours of that activity recorded (all people, "
        "including recordings with no bouts). Single motions, no pair rule or other gate. Continuous motion is cut "
        "into pieces of up to 12 s, and a live detector would cut it finer, so for walking/running/chewing these are "
        "still lower bounds.", "", fa_tab.sort_values("false_messages_per_hour", ascending=False)
        .to_markdown(floatfmt=".2f"), ""]

(OUT / "phase0_report.md").write_text("\n".join(out), encoding="utf-8")
print("\n".join(out))
