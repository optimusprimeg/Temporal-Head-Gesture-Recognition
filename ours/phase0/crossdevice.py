"""Cross-device test: EarSet earbud (30 people) <-> AirPods Pro 2 (4 people) -> results/crossdevice_report.md

Shared classes: nod, tilt (AirPods: tilt left + right), none (EarSet: face + negative recordings; AirPods: idle).
Train on one device, test on the other, in each frame and with two feature sets:
  all  : the 10 features
  axis : only which-axis features (share_x/y/z, planarity), which Phase 0 found to be gesture, not person
Run build_bouts.py and airpods.py first.
"""
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import f1_score
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from earset import HEAD
from features import NAMES

OUT = Path(__file__).resolve().parent / "results"
E = pd.read_csv(OUT / "bouts.csv")
A = pd.read_csv(OUT / "airpods_bouts.csv")
E["y"] = np.where(E.activity.isin(HEAD), E.activity, "none")
E = E[E.y != "shake"]  # no shake in the AirPods data
A = A[A.activity.isin(["nod", "tilt", "idle"])].copy()
A["y"] = A.activity.replace({"idle": "none"})
E["device"], A["device"] = "EarSet", "AirPods"

FEATS = {"all": NAMES, "axis": ["share_x", "share_y", "share_z", "planarity"]}
TASKS = {"nod vs tilt": ["nod", "tilt"], "nod / tilt / none": ["nod", "tilt", "none"]}


def model():
    return make_pipeline(StandardScaler(), LogisticRegression(max_iter=2000, class_weight="balanced"))


def score(y, p):
    r = {"accuracy": np.mean(p == y), "macro_F1": f1_score(y, p, average="macro")}
    for c in sorted(set(y)):
        r[f"recall_{c}"] = np.mean(p[y == c] == c)
    return r


rows, per_person = [], []
for tname, classes in TASKS.items():
    e, a = E[E.y.isin(classes)], A[A.y.isin(classes)]
    for fr in ("R0", "R1", "R2"):
        for fs, names in FEATS.items():
            cols = [f"{fr}_{n}" for n in names]
            key = {"task": tname, "frame": fr, "features": fs}
            # 1. EarSet -> AirPods
            p = model().fit(e[cols], e.y).predict(a[cols])
            rows.append({**key, "train -> test": "EarSet (30) -> AirPods (4)", **score(a.y.to_numpy(), p)})
            for person, ok in pd.Series(p == a.y.to_numpy()).groupby(a.person.to_numpy()).mean().items():
                per_person.append({**key, "person": person, "accuracy": ok})
            # 2. AirPods -> EarSet
            p = model().fit(a[cols], a.y).predict(e[cols])
            rows.append({**key, "train -> test": "AirPods (4) -> EarSet (30)", **score(e.y.to_numpy(), p)})
            # 3. same device, leave one person out (reference)
            p = np.empty(len(a), dtype=object)
            for person in a.person.unique():
                te = (a.person == person).to_numpy()
                p[te] = model().fit(a[cols][~te], a.y[~te]).predict(a[cols][te])
            rows.append({**key, "train -> test": "AirPods LOSO (3 -> 1)", **score(a.y.to_numpy(), p)})
            # 4. EarSet + 3 AirPods people -> 4th AirPods person
            for person in a.person.unique():
                te = (a.person == person).to_numpy()
                tr = pd.concat([e, a[~te]])
                p[te] = model().fit(tr[cols], tr.y).predict(a[cols][te])
            rows.append({**key, "train -> test": "EarSet + 3 AirPods -> 1 AirPods", **score(a.y.to_numpy(), p)})

res = pd.DataFrame(rows)
pp = pd.DataFrame(per_person).pivot_table(index=["task", "frame", "features"], columns="person", values="accuracy")
main = res.pivot_table(index=["task", "frame", "features"], columns="train -> test", values="accuracy", sort=False)

out = ["# Cross-device test: EarSet in-ear prototype <-> AirPods Pro 2", "",
       "Generated by `phase0/crossdevice.py`. Bouts and features from `build_bouts.py` (EarSet, 30 people, left ear, "
       "2 min continuous per motion) and `airpods.py` (AirPods Pro 2, 4 people, cued 2.5 s takes of double nod / "
       "double tilt left+right / idle). Logistic regression, nothing tuned. Frames: R0 sensor axes, R1 gravity, "
       "R2 head frame from 3 calibration nods per person (excluded from testing). Features: `all` = 10 features, "
       "`axis` = only which-axis-the-head-rotates-about (4 features).", "",
       "Note the protocols differ too (continuous repetition vs single cued double gestures; EarSet `none` is face "
       "and daily-life motion, AirPods `none` is idle takes with talking and looking around).", "",
       "## Accuracy", "", main.to_markdown(floatfmt=".2f"), "",
       "## EarSet -> AirPods, accuracy per AirPods person", "", pp.to_markdown(floatfmt=".2f"), "",
       "## All metrics", "", res.set_index(["task", "frame", "features", "train -> test"]).to_markdown(floatfmt=".2f"),
       ""]
(OUT / "crossdevice_report.md").write_text("\n".join(out), encoding="utf-8")
print("\n".join(out[:12]))
